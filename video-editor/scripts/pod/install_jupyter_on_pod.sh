#!/usr/bin/env bash
# Install JupyterLab 4.x on the Vast.ai ComfyUI pod, plus register ipykernel
# entries for the three existing service venvs (ComfyUI, ACE-Step, vLLM-TTS).
#
# After this script runs, use start_jupyter.sh to launch the notebook server
# (bound to 127.0.0.1:8888; expose via the local SSH tunnel).
set -euo pipefail

JUPYTER_DIR="/workspace/jupyter"
LOG_FILE="/workspace/jupyter_install.log"

# uv's rustls/webpki root store sometimes rejects PyPI's Let's Encrypt chain on
# this pod. Point it to the system CA bundle to avoid spurious TLS errors.
export SSL_CERT_FILE="${SSL_CERT_FILE:-/etc/ssl/certs/ca-certificates.crt}"

{
echo "=== Jupyter setup started at $(date -u +%Y-%m-%dT%H:%M:%SZ) ==="

if [[ ! -d "$JUPYTER_DIR" ]]; then
    echo "Creating $JUPYTER_DIR..."
    mkdir -p "$JUPYTER_DIR"
fi

cd "$JUPYTER_DIR"

# Pin a Python that matches the other venvs on this pod (3.12 is what
# ACE-Step and ComfyUI use; vLLM-TTS uses 3.10 but the kernels are
# registered per-venv so the Jupyter server's Python is independent).
uv venv --python 3.12 .venv

# Install JupyterLab + the things you actually use day-to-day.
# `notebook` keeps the classic .ipynb UX as a fallback inside JupyterLab.
# `ipykernel` is required to register the per-service venvs as kernels below.
source .venv/bin/activate
uv pip install \
    "jupyterlab==4.4.4" \
    "notebook==7.4.4" \
    "ipykernel==6.31.0" \
    "jupyterlab-lsp==5.2.0" \
    "python-lsp-server[all]==1.13.0" \
    "ipywidgets==8.1.7" \
    "nbconvert==7.16.6"

# Write a default config so start_jupyter.sh doesn't have to recreate it
# every boot. Token is regenerated per start (see start_jupyter.sh) for
# security: anyone with a previous token URL would otherwise keep access.
mkdir -p /root/.jupyter
cat > /root/.jupyter/jupyter_lab_config.py <<'EOF'
# Auto-generated by install_jupyter_on_pod.sh — do not edit by hand.
c = get_config()  # noqa: F821

# Bind to localhost only; expose via SSH tunnel.
c.ServerApp.ip = "127.0.0.1"
c.ServerApp.port = 8888
c.ServerApp.open_browser = False
c.ServerApp.allow_root = True
c.ServerApp.root_dir = "/workspace"

# Token is set by start_jupyter.sh via JUPYTER_TOKEN env var.
# Password auth is intentionally disabled — single-user pod, SSH tunnel only.
c.ServerApp.password = ""
c.ServerApp.token = ""
EOF

# Register the three service venvs as named Jupyter kernels so the kernel
# picker in the notebook UI lets you pick the right env per notebook.
# We use `uv pip install --python` so we don't have to activate each venv.
register_kernel() {
    local venv_path="$1"
    local display_name="$2"
    if [[ ! -x "$venv_path/bin/python" ]]; then
        echo "  skip $display_name: $venv_path/bin/python not found"
        return 0
    fi
    echo "  register kernel: $display_name  ($venv_path)"
    "$JUPYTER_DIR/.venv/bin/python" -m ipykernel install \
        --name "$(echo "$display_name" | tr 'A-Z' 'a-z' | tr -cd 'a-z0-9-')" \
        --display-name "$display_name" \
        --prefix "$JUPYTER_DIR/.venv"
}

echo "Registering per-service kernels..."
register_kernel "/workspace/ComfyUI/.venv"                    "ComfyUI (PyTorch)"
register_kernel "/workspace/ACE-Step-1.5/.venv"               "ACE-Step 1.5"
register_kernel "/workspace/vllm-tts-backend/.venv"          "vLLM-TTS (Indic-Mio)"

echo "=== Setup complete at $(date -u +%Y-%m-%dT%H:%M:%SZ) ==="
echo
echo "Next: bash scripts/start_jupyter.sh  (on the pod)"
echo "Then add -L 8888:127.0.0.1:8888 to your local SSH tunnel."
} 2>&1 | tee "$LOG_FILE"
